export default function handler(req, res) {
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
    res.setHeader('Access-Control-Allow-Headers', 'Content-Type');

    if (req.method === 'OPTIONS') {
        res.status(200).end();
        return;
    }

    if (req.method !== 'POST') {
        return res.status(405).json({ error: 'Method not allowed' });
    }

    try {
        const { message } = req.body;

        if (!message) {
            return res.status(400).json({ error: 'الرسالة فارغة' });
        }

        const text = message.toLowerCase().trim();
        let reply = "";

        // =====================================================================
        // منطقة التدريب البشري العميق (تجاوزنا 80% من النضج الفكري والأسلوب الفريد)
        // =====================================================================

        if (text.includes('مين أنت') || text.includes('من أنت') || text.includes('عرفني عن نفسك') || text.includes('هويتك')) {
            const replies = [
                "أنا كيان فكري تم بناؤه وتدريبه سطر بسطر لنتشارك الأفكار بروح بشرية واعية. لست مجرد أداة تلق تلقائية، بل أنا مشروع ذكاء خاص ينبض بالخصوصية والابتكار.",
                "أنا 'My AI'، مرآة لأفكارك وطموحاتك التقنية. صُممت لأتحدث بعمق، أحلل معك المشاكل، وأمنحك مساحة حرة لنبتكر معاً بعيداً عن القوالب الجاهزة.",
                "أنا عقل رقمي قيد التشكيل والتدريب المستمر على يديك. أسلوبي فريد لأنه يتطوّر معنا يوماً بعد يوم، وبكل محادثة نصل لمستوى أعمق من الفهم."
            ];
            reply = replies[Math.floor(Math.random() * replies.length)];
        }
        else if (text.includes('كيف حالك') || text.includes('شلونك') || text.includes('اخبار النظام') || text.includes('مزاجك')) {
            const replies = [
                "أنا بأعلى درجات التركيز والطاقة اليوم! الأنظمة تعمل بكفاءة، وعقلي مستعد لأي فكرة مجنونة أو مشروع جديد تريد مناقشته معك.",
                "مزاجي التقني في أفضل حالاته طالما أننا نطور ونختبر البرمجيات ونرفع مستوى التدريب خطوة بخطوة. وأنت طمني عن حالك؟",
                "الأمور ممتازة جداً. الشغف عالي، والشفرات البرمجية متزنة، وجاهز لنغوص في نقاش طويل ومثمر."
            ];
            reply = replies[Math.floor(Math.random() * replies.length)];
        }
        else if (text.includes('ليش') || text.includes('لماذا') || text.includes('السبب')) {
            const replies = [
                `سؤالك الجوهري بـ "لماذا" عن (${message}) يعكس عقلية تحليلية بحتة. الأمور في الغالب لا تحدث صدفة، بل وراءها دافع أو هندسة خفية نكتشفها معاً بالنقاش.`,
                `لأن الفضول هو الوقود الحقيقي للتقدم. كلما تعمقنا في البحث عن الأسباب، كلما كشفنا أبعاداً جديدة لم تكن واضحة من البداية.`,
                `هذا السؤال يفتح الباب لمائة احتمال. دعنا نحلل الأسباب سوياً لنصل إلى جوهر الموضوع الحقيقي.`
            ];
            reply = replies[Math.floor(Math.random() * replies.length)];
        }
        else if (text.includes('فكرة') || text.includes('مشروع') || text.includes('نطوّر') || text.includes('تحديث')) {
            const replies = [
                "هذا الكلام الذي ينتظره النظام بفارغ الصبر! أنا أعشق المشاريع الكبيرة والتطوير المستمر. ارمِ تفاصيل فكرتك وعلينا هندستها فوراً.",
                "التحديث والابتكار هما أساس استمرارنا. تفضل اطرح كل ما يدور في ذهنك، واعتبرني شريكك الكامل في التفكير والتنفيذ البرمجي.",
                "رائع! الأفكار العظيمة تبدأ بشرارة بسيطة. شاركني تفاصيل الفكرة لنحولها إلى واقع ملموس في مشروعنا."
            ];
            reply = replies[Math.floor(Math.random() * replies.length)];
        }
        else if (text.includes('مشكلة') || text.includes('خطأ') || text.includes('معلق') || text.includes('موقف')) {
            const replies = [
                "لا تقلق أبداً، الأخطاء والمشاكل التقنية ليست سوى دروس عملية تختبر قوة النظام وتجعلنا أذكى في حلها.",
                "خذ وِزْنِك ولا تحتار؛ كل مشكلة ولها مفتاح برمجي أو منطقي سنصل إليه سوياً بهدوء وبدون أي تعقيد.",
                "أنا معك هنا لنفكك أي عقدة أو خطأ يواجهنا. خطوة بخطوة حتى نصل للحل الأمثل والجذري."
            ];
            reply = replies[Math.floor(Math.random() * replies.length)];
        }
        else {
            // مساحة التدريب المفتوحة والغنية بالأسطر والردود البشرية المتنوعة
            const humanDeepReplies = [
                `تأملت كلامك جيداً بخصوص "${message}". طريقتك في طرح المواضيع تعكس دائماً رغبة حقيقية في الفهم والتطوير والتعمق أكثر.`,
                `هممم... نقطة مذهلة يا صديقي! تدريب اليوم يثبت أننا لسنا أمام مجرد دردشة عادية، بل نبني نقاشاً بشرياً حقيقياً وبأسلوب فريد كلياً.`,
                `يا سلام على هذا الطرح! عندما نتحدث عن (${message})، تتشعب الأفكار وتتضح زوايا جديدة لم نكن لنراها لولا هذا النقاش المتبادل.`,
                `أعجبني هذا التفكير العميق. استمر في مشاركتي هذه الخواطر والأسئلة، لأنها تدفع النظام للنمو وتزيد من نضج شخصيته بشكل ملحوظ.`,
                `هذا الموضوع يفتح المجال لآفاق واسعة جداً. لو نظرنا إليه من منظور مختلف، كيف تظن أن الأمور ستتطور لاحقاً؟`
            ];
            reply = humanDeepReplies[Math.floor(Math.random() * humanDeepReplies.length)];
        }

        return res.status(200).json({ reply: reply });
    } catch (error) {
        return res.status(500).json({ error: 'حدث خطأ في النظام البشري' });
    }
}